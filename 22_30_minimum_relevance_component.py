def parse_list(value, field):
    if isinstance(value, list):
        return value

    if isinstance(value, tuple):
        return list(value)

    if isinstance(value, np.ndarray):
        return value.tolist()

    text = str(value).strip()

    try:
        result = json.loads(text)
    except Exception:
        try:
            result = ast.literal_eval(text)
        except Exception as exc:
            raise ValueError(
                f"Cannot parse {field}: {text[:120]}"
            ) from exc

    if not isinstance(result, (list, tuple)):
        raise ValueError(
            f"{field} is not a list"
        )

    return list(result)


def normalize_category(value):
    return (
        " ".join(
            str(value)
            .strip()
            .casefold()
            .split()
        )
    )


def parse_categories(value):
    if value is None or pd.isna(value):
        return []

    text = str(value).strip()

    if not text:
        return []

    # Profiles generated by the previous category audit use
    # pipe/semicolon separated genre strings.
    if "|" in text:
        parts = text.split("|")
    elif ";" in text:
        parts = text.split(";")
    elif "," in text:
        parts = text.split(",")
    else:
        parts = [text]

    return sorted(
        {
            normalize_category(x)
            for x in parts
            if str(x).strip()
        }
    )


