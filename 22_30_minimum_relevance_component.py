def main():

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--catalog",
        type=Path,
        default=DEFAULT_CATALOG,
    )

    parser.add_argument(
        "--profiles",
        type=Path,
        default=DEFAULT_PROFILES,
    )

    parser.add_argument(
        "--mapping",
        type=Path,
        default=DEFAULT_MAPPING,
    )

    parser.add_argument(
        "--candidates",
        type=Path,
        default=DEFAULT_CANDIDATES,
    )

    parser.add_argument(
        "--kg",
        type=Path,
        default=DEFAULT_KG,
    )

    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
    )

    args = parser.parse_args()

    args.out.mkdir(
        parents=True,
        exist_ok=True
    )

    print("=" * 72)
    print("EXPERIMENT 22.30")
    print("MINIMUM OPERATIONAL RELEVANCE COMPONENT")
    print("=" * 72)

    # --------------------------------------------------
    # Load frozen data
    # --------------------------------------------------

    movie_ids, item2group = load_catalog(
        args.catalog
    )

    catalog_set = set(movie_ids)

    categories, category_column = load_categories(
        args.profiles,
        catalog_set
    )

    candidates = load_candidates(
        args.candidates
    )

    kg_ranks, kg_rank_column = load_kg(
        args.kg
    )

    # --------------------------------------------------
    # Alignment checks
    # --------------------------------------------------

    candidate_events = set(
        candidates
    )

    kg_events = set(
        kg_ranks
    )

    if candidate_events != kg_events:
        raise RuntimeError(
            "Candidate and KG event IDs do not match."
        )

    if len(candidate_events) != EXPECTED_EVENTS:
        raise RuntimeError(
            "Incorrect event count."
        )

    conversations = {
        int(v["conv_id"])
        for v in candidates.values()
    }

    if len(conversations) != EXPECTED_CONVERSATIONS:
        raise RuntimeError(
            "Incorrect conversation count."
        )

    # --------------------------------------------------
    # Category coverage
    # --------------------------------------------------

    categorized_catalog = sum(
        bool(categories.get(movie_id))
        for movie_id in movie_ids
    )

    category_coverage = (
        categorized_catalog
        / CATALOG_SIZE
    )

    # --------------------------------------------------
    # Reconstruct proposal quantities
    # --------------------------------------------------

    relevance_detail, relevance_mass = (
        reconstruct_relevance_mass(
            candidates,
            kg_ranks,
            categories,
            item2group,
        )
    )

    exposure_detail, exposure_mass = (
        reconstruct_exposure(
            candidates,
            categories,
            item2group,
        )
    )

    rho = calculate_rho(
        relevance_mass,
        exposure_mass,
    )

    # --------------------------------------------------
    # Support sensitivity
    # --------------------------------------------------

    support_rows = []

    for rmin in (
        0.0,
        0.01,
        0.05,
        0.10,
        0.25,
        0.50,
        1.0,
    ):

        active = rho[
            rho["R_cg_proxy"] >= rmin
        ]

        support_rows.append({
            "R_min": rmin,
            "active_cells": int(len(active)),
            "active_categories": int(
                active["category"].nunique()
            ) if len(active) else 0,
            "active_groups": int(
                active[
                    "popularity_group"
                ].nunique()
            ) if len(active) else 0,
        })

    support = pd.DataFrame(
        support_rows
    )

    # --------------------------------------------------
    # Omega is intentionally NOT invented.
    # --------------------------------------------------

    # Proposal Eq. (24) requires omega_c, but the proposal
    # does not provide an operational numerical definition
    # sufficient to justify choosing one here.
    #
    # Therefore we do NOT calculate a claimed final L_fair.

    omega_status = (
        "UNSPECIFIED_IN_PROPOSAL_FOR_OPERATIONAL_IMPLEMENTATION"
    )

    # --------------------------------------------------
    # Validation
    # --------------------------------------------------

    validation = {
        "events": len(candidates),
        "conversations": len(conversations),
        "catalog_items": len(movie_ids),
        "categorized_catalog_items": categorized_catalog,
        "category_coverage": category_coverage,
        "candidate_pool_size": 500,
        "exposure_top_k": TOP_K,
        "kg_rank_source": kg_rank_column,
        "tau": TAU,
        "q_definition": (
            "22.18 candidate-pool category context "
            "* exp(-KG-rank/tau)"
        ),
        "q_is_validated_semantic_relevance": False,
        "q_uses_test_target": False,
        "q_uses_future_exposure": False,
        "ranking_modified": False,
        "retrieval_rerun": False,
        "training": False,
        "parameter_optimization": False,
        "R_cg_proxy_reconstructed": True,
        "rho_cg_proxy_reconstructed": True,
        "omega_c_operationally_specified": False,
        "L_fair_final_identifiable": False,
    }

    # --------------------------------------------------
    # Save outputs
    # --------------------------------------------------

    relevance_detail.to_csv(
        args.out
        / "event_item_q_proxy.csv",
        index=False,
    )

    relevance_mass.to_csv(
        args.out
        / "R_cg_proxy.csv",
        index=False,
    )

    exposure_mass.to_csv(
        args.out
        / "E_cg.csv",
        index=False,
    )

    rho.to_csv(
        args.out
        / "rho_cg_proxy.csv",
        index=False,
    )

    support.to_csv(
        args.out
        / "R_min_support_sensitivity.csv",
        index=False,
    )

    with open(
        args.out / "validation.json",
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            validation,
            f,
            indent=2,
        )

    decision = {
        "experiment": "22.30",
        "q_status": (
            "OPERATIONAL_PROXY_AVAILABLE"
        ),
        "q_validation_status": (
            "NOT_VALIDATED_AS_DIALOGUE_SEMANTIC_RELEVANCE"
        ),
        "R_cg_status": (
            "RECONSTRUCTABLE_AS_PROXY"
        ),
        "rho_cg_status": (
            "RECONSTRUCTABLE_AS_PROXY"
        ),
        "omega_c_status": omega_status,
        "L_fair_status": (
            "NOT_FINAL_IDENTIFIABLE"
        ),
        "minimum_remaining_work": [
            "Validate q_proxy against an independent "
            "contextual relevance signal.",
            "Define omega_c operationally.",
            "Pre-specify R_min.",
            "Then calculate the final proposal L_fair."
        ],
        "scientific_interpretation": (
            "22.30 establishes an operational bridge "
            "from frozen KG/context evidence to R_cg, "
            "but does not establish that the existing "
            "proxy is the proposal's validated contextual "
            "relevance q_ei."
        ),
    }

    with open(
        args.out / "decision_gate.json",
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            decision,
            f,
            indent=2,
        )

    print()
    print("=" * 72)
    print("22.30 COMPLETE")
    print("=" * 72)

    print(
        f"Catalog category coverage: "
        f"{categorized_catalog}/{CATALOG_SIZE} "
        f"({category_coverage:.2%})"
    )

    print(
        f"Positive q-proxy R_cg cells: "
        f"{len(relevance_mass)}"
    )

    print(
        f"R_cg: RECONSTRUCTABLE_AS_PROXY"
    )

    print(
        f"rho_cg: RECONSTRUCTABLE_AS_PROXY"
    )

    print(
        f"omega_c: {omega_status}"
    )

    print(
        "L_fair: NOT_FINAL_IDENTIFIABLE"
    )

    print()
    print(
        "Read-only: YES | "
        "Training: NO | "
        "Retrieval: NO | "
        "Ranking changes: NO"
    )

    print()
    print(
        "Output:",
        args.out.resolve()
    )


if __name__ == "__main__":
    main()