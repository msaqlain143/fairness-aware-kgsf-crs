def load_categories(path, catalog_ids):
    df = pd.read_csv(path)

    required = {"movie_entity_id"}

    missing = required - set(df.columns)

    if missing:
        raise RuntimeError(
            f"Category profile missing columns: "
            f"{sorted(missing)}"
        )

    # Prefer the canonical audited genre field.
    category_column = None

    for candidate in (
        "canonical_genres",
        "accepted_genre_evidence",
        "imdb_genres",
    ):
        if candidate in df.columns:
            category_column = candidate
            break

    if category_column is None:
        raise RuntimeError(
            "No usable category column found."
        )

    categories = {}

    for _, row in df.iterrows():

        movie_id = int(row["movie_entity_id"])

        if movie_id not in catalog_ids:
            continue

        categories[movie_id] = parse_categories(
            row[category_column]
        )

    return categories, category_column


# ---------------------------------------------------------------------
# Frozen candidates
# ---------------------------------------------------------------------

def load_candidates(path):
    df = pd.read_csv(path)

    required = {
        "event_id",
        "conv_id",
        "target_movie_id",
        "top_movie_ids",
        "top_scores",
    }

    missing = required - set(df.columns)

    if missing:
        raise RuntimeError(
            f"Candidate export missing columns: "
            f"{sorted(missing)}"
        )

    if len(df) != EXPECTED_EVENTS:
        raise RuntimeError(
            f"Expected {EXPECTED_EVENTS} events; "
            f"got {len(df)}"
        )

    if df.event_id.duplicated().any():
        raise RuntimeError(
            "Duplicate event IDs."
        )

    result = {}

    for _, row in df.iterrows():

        event_id = int(row.event_id)

        movie_ids = np.asarray(
            [
                int(x)
                for x in parse_list(
                    row.top_movie_ids,
                    "top_movie_ids"
                )
            ],
            dtype=np.int64,
        )

        scores = np.asarray(
            [
                float(x)
                for x in parse_list(
                    row.top_scores,
                    "top_scores"
                )
            ],
            dtype=np.float64,
        )

        if len(movie_ids) != 500:
            raise RuntimeError(
                f"Event {event_id}: expected 500 candidates."
            )

        if len(scores) != 500:
            raise RuntimeError(
                f"Event {event_id}: expected 500 scores."
            )

        result[event_id] = {
            "conv_id": int(row.conv_id),
            "target_movie_id": int(row.target_movie_id),
            "ids": movie_ids,
            "scores": scores,
        }

    return result


