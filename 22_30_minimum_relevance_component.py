def load_kg(path):
    df = pd.read_csv(path)

    required = {
        "event_id",
        "conv_id",
        "target_movie_id",
    }

    missing = required - set(df.columns)

    if missing:
        raise RuntimeError(
            f"KG export missing columns: "
            f"{sorted(missing)}"
        )

    # 22.27A2 contains graph-specific candidate rank vectors.
    rank_column = None

    for candidate in (
        "R1_raw_candidate_kg_ranks",
        "R0_filtered_candidate_kg_ranks",
        "candidate_kg_ranks",
    ):
        if candidate in df.columns:
            rank_column = candidate
            break

    if rank_column is None:
        raise RuntimeError(
            "No candidate-aligned KG rank column found. "
            "Expected R1_raw_candidate_kg_ranks or "
            "R0_filtered_candidate_kg_ranks."
        )

    if len(df) != EXPECTED_EVENTS:
        raise RuntimeError(
            f"Expected {EXPECTED_EVENTS} KG events; "
            f"got {len(df)}"
        )

    result = {}

    for _, row in df.iterrows():

        event_id = int(row.event_id)

        ranks = np.asarray(
            [
                int(x)
                for x in parse_list(
                    row[rank_column],
                    rank_column
                )
            ],
            dtype=np.int64,
        )

        if len(ranks) != 500:
            raise RuntimeError(
                f"Event {event_id}: KG rank vector "
                f"must contain 500 values."
            )

        result[event_id] = ranks

    return result, rank_column


# ---------------------------------------------------------------------
# Candidate-pool category context
# ---------------------------------------------------------------------

def category_context(candidate_ids, categories):
    """
    Exact conceptual definition inherited from 22.18:

        category prevalence within the frozen candidate pool,
        normalized by the maximum category prevalence.

    Multi-label membership is divided by the number of categories
    attached to the item.
    """

    counts = {}
    categorized_items = 0

    for movie_id in candidate_ids:

        movie_categories = categories.get(
            int(movie_id),
            []
        )

        if not movie_categories:
            continue

        categorized_items += 1

        weight = 1.0 / len(movie_categories)

        for category in movie_categories:
            counts[category] = (
                counts.get(category, 0.0)
                + weight
            )

    if categorized_items == 0:
        return {}, 0

    prevalence = {
        category: value / categorized_items
        for category, value in counts.items()
    }

    maximum = max(
        prevalence.values(),
        default=0.0
    )

    if maximum <= EPS:
        return {}, categorized_items

    normalized = {
        category: value / maximum
        for category, value in prevalence.items()
    }

    return normalized, categorized_items


# ---------------------------------------------------------------------
# q proxy
# ---------------------------------------------------------------------

def compute_q(candidate_ids, kg_ranks, categories):
    """
    Existing 22.18 contextual-KG proxy:

        q_proxy(e,i)
          = context_i * exp(-rank_i / tau)

    Unsupported KG items receive zero.

    IMPORTANT:
    This is NOT claimed to be validated semantic relevance.
    """

    context, categorized_count = category_context(
        candidate_ids,
        categories
    )

    q = np.zeros(
        len(candidate_ids),
        dtype=np.float64
    )

    supported = 0

    for j, movie_id in enumerate(candidate_ids):

        movie_categories = categories.get(
            int(movie_id),
            []
        )

        rank = int(kg_ranks[j])

        if not movie_categories:
            continue

        if rank <= 0:
            continue

        supported += 1

        context_value = float(
            np.mean(
                [
                    context.get(category, 0.0)
                    for category in movie_categories
                ]
            )
        )

        kg_confidence = math.exp(
            -float(rank) / TAU
        )

        q[j] = (
            context_value
            * kg_confidence
        )

    return q, categorized_count, supported


# ---------------------------------------------------------------------
# Proposal R_cg
# ---------------------------------------------------------------------

def reconstruct_relevance_mass(
    candidates,
    kg_ranks,
    categories,
    item2group,
):
    """
    Reconstruct proposal Eq. (21):

        R_c,g =
            sum_e sum_i
            q_e,i A_i,c
            I(g(i)=g)
            I(i in I_e)

    Here I_e is operationalized as the frozen Top-500
    candidate opportunity set.

    q is explicitly labelled q_proxy.
    """

    rows = []

    for event_id in sorted(candidates):

        candidate = candidates[event_id]

        ids = candidate["ids"]
        ranks = kg_ranks[event_id]

        q, categorized_count, supported = compute_q(
            ids,
            ranks,
            categories
        )

        for movie_id, q_value in zip(ids, q):

            if q_value <= 0:
                continue

            movie_categories = categories.get(
                int(movie_id),
                []
            )

            group = int(
                item2group[int(movie_id)]
            )

            for category in movie_categories:

                rows.append({
                    "event_id": int(event_id),
                    "conv_id": int(
                        candidate["conv_id"]
                    ),
                    "movie_id": int(movie_id),
                    "category": category,
                    "popularity_group": group,
                    "q_proxy": float(q_value),
                })

    detail = pd.DataFrame(rows)

    if detail.empty:
        raise RuntimeError(
            "No positive q_proxy relevance mass."
        )

    mass = (
        detail
        .groupby(
            ["category", "popularity_group"],
            as_index=False
        )["q_proxy"]
        .sum()
        .rename(
            columns={
                "q_proxy": "R_cg_proxy"
            }
        )
    )

    return detail, mass


# ---------------------------------------------------------------------
# Exposure E_cg
# ---------------------------------------------------------------------

def reconstruct_exposure(
    candidates,
    categories,
    item2group,
):
    """
    Proposal Eq. (22):

        E_c,g =
            sum_e sum_r
            w(r)
            A_pi[r],c
            I(g(pi[r])=g)

    The frozen KGSF Top-10 is used as pi_e.
    No reranking occurs.
    """

    rows = []

    for event_id in sorted(candidates):

        candidate = candidates[event_id]

        ids = candidate["ids"]

        for position, movie_id in enumerate(
            ids[:TOP_K],
            start=1
        ):

            weight = 1.0 / math.log2(
                position + 1.0
            )

            movie_categories = categories.get(
                int(movie_id),
                []
            )

            if not movie_categories:
                continue

            group = int(
                item2group[int(movie_id)]
            )

            # Multi-label category exposure is divided
            # across the item's verified categories.
            category_weight = (
                1.0 / len(movie_categories)
            )

            for category in movie_categories:

                rows.append({
                    "event_id": int(event_id),
                    "category": category,
                    "popularity_group": group,
                    "exposure": (
                        weight * category_weight
                    ),
                })

    detail = pd.DataFrame(rows)

    exposure = (
        detail
        .groupby(
            ["category", "popularity_group"],
            as_index=False
        )["exposure"]
        .sum()
        .rename(
            columns={
                "exposure": "E_cg"
            }
        )
    )

    return detail, exposure


# ---------------------------------------------------------------------
# rho
# ---------------------------------------------------------------------

def calculate_rho(mass, exposure):
    merged = pd.merge(
        mass,
        exposure,
        on=[
            "category",
            "popularity_group",
        ],
        how="outer",
    )

    merged["R_cg_proxy"] = (
        merged["R_cg_proxy"]
        .fillna(0.0)
    )

    merged["E_cg"] = (
        merged["E_cg"]
        .fillna(0.0)
    )

    merged["rho_cg_proxy"] = (
        merged["E_cg"]
        /
        (
            merged["R_cg_proxy"]
            + EPS
        )
    )

    return merged


