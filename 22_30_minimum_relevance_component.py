#!/usr/bin/env python
"""
Experiment 22.30
Minimum Operational Relevance Component

Purpose
-------
Operationalize the existing frozen 22.18 contextual-KG relevance proxy
against the independent-test candidate universe so that the proposal's
R_{c,g} and rho_{c,g} can be reconstructed.

IMPORTANT
---------
This experiment does NOT claim that the proxy is validated semantic
dialogue relevance.

It uses only information available at recommendation event e:

    q_proxy(e,i)
        = category_context(e,i)
          * exp(-KG_rank(e,i) / tau)

where:

    category_context(e,i)
        = mean normalized category prevalence in the event's frozen
          Top-500 candidate pool.

    KG confidence
        = exp(-KG_rank / tau)

Unsupported KG candidates have q_proxy = 0.

No:
    - training
    - retrieval
    - reranking
    - parameter optimization
    - target-assisted relevance construction
    - modification of frozen results

is performed.

The ground-truth target is NOT used anywhere in q construction.
"""

