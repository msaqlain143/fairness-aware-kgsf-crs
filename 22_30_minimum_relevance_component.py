def load_catalog(path):
    with path.open("rb") as f:
        catalog = pickle.load(f)

    movie_ids = [
        int(x)
        for x in catalog["movie_ids"]
    ]

    if len(movie_ids) != CATALOG_SIZE:
        raise RuntimeError(
            f"Expected {CATALOG_SIZE} catalog items; "
            f"got {len(movie_ids)}"
        )

    if len(set(movie_ids)) != CATALOG_SIZE:
        raise RuntimeError(
            "Catalog movie IDs are not unique."
        )

    item2group = {
        int(k): int(v)
        for k, v in catalog["item2group"].items()
    }

    if set(item2group) != set(movie_ids):
        raise RuntimeError(
            "item2group does not exactly match catalog."
        )

    return movie_ids, item2group


