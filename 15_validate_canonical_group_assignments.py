"""Experiment 15: canonical catalog-to-exposure validation.

This audit validates frozen recommendations against the supplied catalog,
reconstructs item/group/cold-start exposure, reproduces frozen metrics, and
records input hashes. It does not train or infer with a model.

IMPORTANT: agreement with catalog['item2group'] proves consistency with the
stored map, not independent correctness of the original quintile construction.
That requires the original sorting, tie-breaking, and group-assignment rule.
"""

