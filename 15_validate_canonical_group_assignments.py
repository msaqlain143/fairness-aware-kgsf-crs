def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        require(reader.fieldnames is not None, f"Missing CSV header: {path}")
        return list(reader), set(reader.fieldnames)


def save_csv(path, rows):
    require(bool(rows), f"Refusing to write empty CSV: {path}")
    with path.open("x", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def parse_list(value, description):
    try:
        result = json.loads(value)
    except (TypeError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"Invalid JSON list: {description}") from exc
    require(isinstance(result, list), f"Expected JSON list: {description}")
    return result


def number(value, field, key):
    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise RuntimeError(f"Invalid {field} for {key}: {value!r}") from exc
    require(math.isfinite(result), f"Non-finite {field} for {key}")
    return result


def gini(counts):
    """Population Gini over all catalog items, including zero-exposure items."""
    x = np.sort(np.asarray(counts, dtype=np.float64))
    n, total = len(x), float(x.sum())
    require(n > 0 and total > 0, "Gini requires a nonempty catalog and positive exposure")
    require(np.all(x >= 0), "Negative item exposure detected")
    coef = 2 * np.arange(1, n + 1) - n - 1
    value = float(np.dot(coef, x) / (n * total))
    require(-TOL <= value <= 1 + TOL, f"Gini outside [0,1]: {value}")
    return value


def compare(name, observed, expected):
    delta = abs(float(observed) - float(expected))
    require(delta <= TOL,
            f"{name} mismatch: observed={observed:.12f}, expected={expected:.12f}, delta={delta:.3e}")


print("=" * 76)
print("EXPERIMENT 15: CANONICAL CATALOG-TO-EXPOSURE VALIDATION")
print("=" * 76)
for path in (CATALOG_FILE, EVENTS_FILE, REFERENCE_FILE):
    require(path.is_file(), f"Missing required input: {path}")

hashes = {
    "catalog_sha256": sha256(CATALOG_FILE),
    "events_sha256": sha256(EVENTS_FILE),
    "reference_sha256": sha256(REFERENCE_FILE),
}

# Load only the trusted pickle generated by this project's own pipeline.
with CATALOG_FILE.open("rb") as f:
    catalog = pickle.load(f)
rows, columns = read_csv(EVENTS_FILE)
with REFERENCE_FILE.open(encoding="utf-8") as f:
    report = json.load(f)

# ---------------------------- Catalog audit ----------------------------
required = {"movie_ids", "freq_dict", "item2group", "zero_shot_ids", "one_shot_ids", "tau"}
require(required.issubset(catalog), f"Missing catalog keys: {sorted(required - set(catalog))}")
movie_list = [int(x) for x in catalog["movie_ids"]]
movie_ids = set(movie_list)
freq = {int(k): int(v) for k, v in catalog["freq_dict"].items()}
item2group = {int(k): int(v) for k, v in catalog["item2group"].items()}
zero = {int(x) for x in catalog["zero_shot_ids"]}
one = {int(x) for x in catalog["one_shot_ids"]}
tau = int(catalog["tau"])

require(len(movie_list) == len(movie_ids), "Duplicate IDs in movie_ids")
require(len(movie_ids) == EXPECTED_CATALOG, "Unexpected catalog size")
require(set(freq) == movie_ids, "Frequency dictionary/catalog key mismatch")
require(set(item2group) == movie_ids, "Group dictionary/catalog key mismatch")
require(all(v >= 0 for v in freq.values()), "Negative training frequency")
require(set(item2group.values()) == set(range(N_GROUPS)), "Invalid group IDs")
require(zero == {m for m, f in freq.items() if f == 0}, "Zero-shot IDs disagree with frequency dictionary")
require(one == {m for m, f in freq.items() if f == 1}, "One-shot IDs disagree with frequency dictionary")
require(zero.isdisjoint(one), "Zero-shot and one-shot sets overlap")

sorted_items_available = "sorted_items" in catalog
if sorted_items_available:
    sorted_items = [int(x) for x in catalog["sorted_items"]]
    require(len(sorted_items) == EXPECTED_CATALOG, "sorted_items length mismatch")
    require(len(set(sorted_items)) == EXPECTED_CATALOG, "Duplicate IDs in sorted_items")
    require(set(sorted_items) == movie_ids, "sorted_items is not a catalog permutation")

group_catalog_counts = Counter(item2group.values())
group_sizes = [int(group_catalog_counts[g]) for g in range(N_GROUPS)]
require(sum(group_sizes) == EXPECTED_CATALOG, "Group sizes do not sum to catalog size")
require(max(group_sizes) - min(group_sizes) <= 1, "Popularity groups are not balanced in size")
catalog_distribution = [
    {"group": g, "catalog_items": group_sizes[g], "catalog_share": group_sizes[g] / EXPECTED_CATALOG}
    for g in range(N_GROUPS)
]

print("\n[1] CATALOG")
print(f"Items={len(movie_ids)} | zero-shot={len(zero)} | one-shot={len(one)} | tau={tau}")
print("Catalog IDs, frequencies, cold-start labels, and stored group-map keys: PASS")
print("Group sizes:", group_sizes)

# ------------------------- Frozen reference audit ----------------------
require(int(report.get("events", -1)) == EXPECTED_EVENTS, "Reference event count mismatch")
require(int(report.get("candidate_movies", -1)) == EXPECTED_CATALOG, "Reference catalog size mismatch")
ref_list = report.get("results")
require(isinstance(ref_list, list), "Reference results must be a list")
ref = {}
for result in ref_list:
    method = result.get("method")
    require(method not in ref, f"Duplicate method in reference: {method}")
    ref[method] = result
require(set(ref) == set(METHODS), "Reference method set mismatch")

expected_columns = {
    "event_id", "method", "target_movie_id", "target_frequency", "frequency_group",
    "target_context_overlap", "context_nonempty", "hit10", "ndcg10",
    "top10_movie_ids", "top10_group_ids",
}
require(expected_columns.issubset(columns), f"Missing event columns: {sorted(expected_columns - columns)}")
require(len(rows) == EXPECTED_EVENTS * len(METHODS), "Event-method row count mismatch")

# ---------------------- Event/target metadata audit --------------------
seen_keys = set()          # Tracks key completeness before recommendations are parsed.
event_metadata = {}
method_counts = Counter()
for row in rows:
    eid = int(row["event_id"])
    method = str(row["method"]).strip()
    key = (eid, method)
    require(1 <= eid <= EXPECTED_EVENTS, f"Out-of-range event ID: {eid}")
    require(method in METHODS, f"Unknown method: {method!r}")
    require(key not in seen_keys, f"Duplicate event-method key: {key}")
    seen_keys.add(key)
    method_counts[method] += 1

    target = int(row["target_movie_id"])
    target_freq = int(row["target_frequency"])
    require(target in movie_ids, f"Target not in catalog: {target}")
    require(target_freq == freq[target], f"Target frequency mismatch: event={eid}, movie={target}")
    expected_class = "zero_shot" if target_freq == 0 else "one_shot" if target_freq == 1 else "other"
    actual_class = str(row["frequency_group"]).strip().lower()
    require(actual_class == expected_class,
            f"Target class mismatch: event={eid}, expected={expected_class}, actual={actual_class}")

    metadata = (target, target_freq, actual_class,
                str(row["target_context_overlap"]).strip(),
                str(row["context_nonempty"]).strip())
    if eid in event_metadata:
        require(event_metadata[eid] == metadata, f"Cross-method metadata mismatch: event={eid}")
    else:
        event_metadata[eid] = metadata

expected_keys = {(eid, method) for eid in range(1, EXPECTED_EVENTS + 1) for method in METHODS}
require(seen_keys == expected_keys,
        f"Event-method pairing mismatch: missing={len(expected_keys-seen_keys)}, unexpected={len(seen_keys-expected_keys)}")
require(set(event_metadata) == set(range(1, EXPECTED_EVENTS + 1)), "Missing event IDs")
require(all(method_counts[m] == EXPECTED_EVENTS for m in METHODS), "Unequal method row counts")
print("\n[2] EVENT AND TARGET METADATA")
print(f"Events={len(event_metadata)} | event-method rows={len(seen_keys)} | methods={len(method_counts)}")
print("Target frequency/classification and cross-method consistency: PASS")

# ------------------------ Recommendation audit ------------------------
records = {}              # Populated only after each top-10 list is validated.
accuracy = {m: {"hit10": [], "ndcg10": []} for m in METHODS}
for row in rows:
    eid = int(row["event_id"])
    method = str(row["method"]).strip()
    key = (eid, method)
    require(key not in records, f"Duplicate recommendation record: {key}")
    movies_raw = parse_list(row["top10_movie_ids"], f"top10_movie_ids {key}")
    groups_raw = parse_list(row["top10_group_ids"], f"top10_group_ids {key}")
    require(len(movies_raw) == TOP_K and len(groups_raw) == TOP_K, f"Top-{TOP_K} length error: {key}")
    movies = [int(x) for x in movies_raw]
    groups = [int(x) for x in groups_raw]
    require(len(set(movies)) == TOP_K, f"Duplicate movie in top-{TOP_K}: {key}")
    for movie, recorded_group in zip(movies, groups):
        require(movie in movie_ids, f"Recommended item not in catalog: {movie}, {key}")
        require(recorded_group == item2group[movie],
                f"Group-map mismatch: event={eid}, method={method}, movie={movie}, "
                f"stored={recorded_group}, canonical_map={item2group[movie]}")
    h = number(row["hit10"], "hit10", key)
    n = number(row["ndcg10"], "ndcg10", key)
    require(0 <= h <= 1, f"Hit@10 outside [0,1]: {key}")
    require(0 <= n <= 1, f"NDCG@10 outside [0,1]: {key}")
    accuracy[method]["hit10"].append(h)
    accuracy[method]["ndcg10"].append(n)
    records[key] = (movies, groups)
require(set(records) == expected_keys, "Validated recommendation records are incomplete")
print("\n[3] RECOMMENDATION LISTS")
print(f"Validated lists={len(records)} | slots={len(records) * TOP_K}")
print("Top-10 uniqueness, catalog membership, and stored group-map consistency: PASS")

# -------------------------- Exposure analysis -------------------------
sorted_ids = sorted(movie_ids)
index = {movie: i for i, movie in enumerate(sorted_ids)}
item_groups = np.array([item2group[m] for m in sorted_ids], dtype=np.int32)
zero_mask = np.array([m in zero for m in sorted_ids], dtype=bool)
one_mask = np.array([m in one for m in sorted_ids], dtype=bool)
other_mask = ~(zero_mask | one_mask)

method_rows = []
group_rows = []
cold_rows = []
item_rows = []
print("\n[4] EXPOSURE AND FROZEN-REFERENCE REPRODUCTION")
for method in METHODS:
    item_exposure = np.zeros(EXPECTED_CATALOG, dtype=np.int64)
    group_exposure = np.zeros(N_GROUPS, dtype=np.int64)
    for eid in range(1, EXPECTED_EVENTS + 1):
        movies, groups = records[(eid, method)]
        for movie, group in zip(movies, groups):
            item_exposure[index[movie]] += 1
            group_exposure[group] += 1

    slots = int(item_exposure.sum())
    require(slots == EXPECTED_EVENTS * TOP_K, f"Exposure slot conservation failed: {method}")
    require(int(group_exposure.sum()) == slots, f"Group slot conservation failed: {method}")
    coverage = float(np.count_nonzero(item_exposure) / EXPECTED_CATALOG)
    inequality = gini(item_exposure)
    shares = group_exposure / slots
    require(np.isclose(shares.sum(), 1.0, atol=1e-12, rtol=0), f"Group shares do not sum to one: {method}")

    hit10 = float(np.mean(accuracy[method]["hit10"]))
    ndcg10 = float(np.mean(accuracy[method]["ndcg10"]))
    r = ref[method]
    compare(f"{method}/hit10", hit10, r["hit10"])
    compare(f"{method}/ndcg10", ndcg10, r["ndcg10"])
    compare(f"{method}/coverage10", coverage, r["catalog_coverage10"])
    compare(f"{method}/item_gini", inequality, r["item_gini"])
    ref_shares = np.asarray(r["group_exposure_shares"], dtype=float)
    require(ref_shares.shape == (N_GROUPS,) and np.all(np.isfinite(ref_shares)),
            f"Invalid reference group-share vector: {method}")
    require(np.isclose(ref_shares.sum(), 1.0, atol=1e-9, rtol=0),
            f"Reference group shares do not sum to one: {method}")
    require(np.allclose(shares, ref_shares, atol=TOL, rtol=0),
            f"Group exposure reference mismatch: {method}")

    for g in range(N_GROUPS):
        mask = item_groups == g
        n_catalog = int(mask.sum())
        n_exposed = int(np.count_nonzero(item_exposure[mask]))
        cat_share = n_catalog / EXPECTED_CATALOG
        exp_share = float(shares[g])
        group_rows.append({
            "method": method,
            "group": g,
            "catalog_items": n_catalog,
            "catalog_share": cat_share,
            "exposed_items": n_exposed,
            "within_group_item_coverage": n_exposed / n_catalog,
            "exposure_slots": int(group_exposure[g]),
            "exposure_share": exp_share,
            "exposure_to_catalog_share_ratio": exp_share / cat_share,
            "mean_exposures_per_catalog_item": int(group_exposure[g]) / n_catalog,
        })

    stratum_masks = [("zero_shot", zero_mask), ("one_shot", one_mask), ("other", other_mask)]
    stratum_summary = {}
    for name, mask in stratum_masks:
        n_items = int(mask.sum())
        exposed = int(np.count_nonzero(item_exposure[mask]))
        exp_slots = int(item_exposure[mask].sum())
        row = {
            "method": method,
            "stratum": name,
            "catalog_items": n_items,
            "exposed_items": exposed,
            "unexposed_items": n_items - exposed,
            "within_stratum_item_coverage": exposed / n_items if n_items else 0.0,
            "exposure_slots": exp_slots,
            "exposure_share": exp_slots / slots,
            "mean_exposures_per_catalog_item": exp_slots / n_items if n_items else 0.0,
            "mean_exposures_per_exposed_item": exp_slots / exposed if exposed else 0.0,
        }
        cold_rows.append(row)
        stratum_summary[name] = row

    for i, movie in enumerate(sorted_ids):
        f = freq[movie]
        stratum = "zero_shot" if f == 0 else "one_shot" if f == 1 else "other"
        item_rows.append({
            "method": method,
            "movie_id": movie,
            "training_frequency": f,
            "popularity_group": int(item_groups[i]),
            "cold_start_stratum": stratum,
            "exposure_count": int(item_exposure[i]),
            "was_exposed": int(item_exposure[i] > 0),
        })

    summary_row = {
        "method": method,
        "events": EXPECTED_EVENTS,
        "catalog_size": EXPECTED_CATALOG,
        "recommendation_slots": slots,
        "unique_exposed_items": int(np.count_nonzero(item_exposure)),
        "catalog_coverage10": coverage,
        "item_gini": inequality,
        "hit10": hit10,
        "ndcg10": ndcg10,
        "zero_shot_catalog_items": int(zero_mask.sum()),
        "zero_shot_exposed_items": stratum_summary["zero_shot"]["exposed_items"],
        "zero_shot_item_coverage": stratum_summary["zero_shot"]["within_stratum_item_coverage"],
        "zero_shot_exposure_share": stratum_summary["zero_shot"]["exposure_share"],
        "one_shot_catalog_items": int(one_mask.sum()),
        "one_shot_exposed_items": stratum_summary["one_shot"]["exposed_items"],
        "one_shot_item_coverage": stratum_summary["one_shot"]["within_stratum_item_coverage"],
        "one_shot_exposure_share": stratum_summary["one_shot"]["exposure_share"],
        "reference_reproduction": "PASS",
    }
    for g in range(N_GROUPS):
        summary_row[f"group_{g}_exposure_share"] = float(shares[g])
    method_rows.append(summary_row)

    print(f"{method:26s} Hit@10={hit10:.6f} NDCG@10={ndcg10:.6f} "
          f"Coverage={coverage:.6f} Gini={inequality:.6f}")
    print(f"  Zero-shot item coverage={stratum_summary['zero_shot']['within_stratum_item_coverage']:.4%}; "
          f"exposure share={stratum_summary['zero_shot']['exposure_share']:.4%}")
    print(f"  One-shot item coverage={stratum_summary['one_shot']['within_stratum_item_coverage']:.4%}; "
          f"exposure share={stratum_summary['one_shot']['exposure_share']:.4%}")
    print("  Frozen reference reproduction: PASS")

# ------------------------------- Outputs -------------------------------
print("\n[5] WRITING AUDIT OUTPUTS")
save_csv(OUT / OUTPUTS[0], group_rows)
save_csv(OUT / OUTPUTS[1], method_rows)
