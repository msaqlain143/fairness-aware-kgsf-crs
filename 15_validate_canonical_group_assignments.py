import hashlib
import json
import math
import pickle
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

# ---------------------------- Configuration ----------------------------
ROOT = Path("results_final_test_m2")
CATALOG_FILE = Path("catalog_audit_corrected.pkl")
EVENTS_FILE = ROOT / "adaptive_m2_with_kgsf_baseline_events.csv"
REFERENCE_FILE = ROOT / "adaptive_m2_with_kgsf_baseline.json"
OUT = Path("results_canonical_group_audit_v2")

METHODS = [
    "KGSF_only", "A0_fixed_025", "A1_frequency_1",
    "A2_frequency_context_1", "A1_frequency_3",
    "A2_frequency_context_3",
]
EXPECTED_EVENTS = 4003
EXPECTED_CATALOG = 6924
N_GROUPS = 5
TOP_K = 10
TOL = 1e-9
OUTPUTS = [
    "canonical_group_exposure.csv",
    "canonical_method_summary.csv",
    "canonical_catalog_distribution.csv",
    "canonical_cold_start_exposure.csv",
    "canonical_item_exposure.csv",
    "canonical_group_validation_summary.json",
]

OUT.mkdir(parents=True, exist_ok=True)
existing = [name for name in OUTPUTS if (OUT / name).exists()]
